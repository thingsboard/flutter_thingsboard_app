"""Generates lib/utils/ui/mdi_icons.g.dart and the Material Design Icons font
from an @mdi/font npm package.

Use the same MDI version as the ThingsBoard web UI (ui-ngx/package.json,
"@mdi/svg"), so icon names chosen there resolve in the app.

    npm pack @mdi/font@7.4.47 && tar xzf mdi-font-7.4.47.tgz
    tool/generate_mdi_icons.py package
"""
import os
import re
import shutil
import sys

pkg = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
scss = open(os.path.join(pkg, 'scss', '_variables.scss'), encoding='utf-8').read()
version = re.search(r'\$mdi-version:\s*"([^"]+)"', scss).group(1)
icons = re.findall(r'^\s*"([a-z0-9-]+)":\s*([0-9A-F]+),?\s*$', scss, re.M)
if not icons:
    sys.exit('no icons found')


def key(name):
    return name.replace('-', '')


seen = {}
for name, _ in icons:
    other = seen.setdefault(key(name), name)
    if other != name:
        sys.exit(f'key collision: {other} / {name}')

lines = [
    '// GENERATED by tool/generate_mdi_icons.py from @mdi/font '
    f'{version}. Do not edit.',
    '// One line per icon, so a version update stays a readable diff.',
    '// dart format off',
    '',
    "import 'package:flutter/widgets.dart';",
    '',
    f"const mdiVersion = '{version}';",
    '',
    "const _family = 'MaterialDesignIcons';",
    '',
    '/// Material Design Icons by name without dashes',
    '/// (`account-circle` -> `accountcircle`). Const instances, so release',
    '/// builds can tree-shake the icon font.',
    'const mdiIcons = <String, IconData>{',
]
lines += [
    f"  '{key(name)}': IconData(0x{code}, fontFamily: _family),  // {name}"
    for name, code in icons
]
lines += ['};', '']
out = os.path.join(root, 'lib', 'utils', 'ui', 'mdi_icons.g.dart')
open(out, 'w', encoding='utf-8').write('\n'.join(lines))

fonts = os.path.join(root, 'assets', 'fonts')
os.makedirs(fonts, exist_ok=True)
shutil.copy(os.path.join(pkg, 'fonts', 'materialdesignicons-webfont.ttf'),
            os.path.join(fonts, 'materialdesignicons-webfont.ttf'))
shutil.copy(os.path.join(pkg, 'LICENSE'),
            os.path.join(fonts, 'materialdesignicons-LICENSE.txt'))
print(f'MDI {version}: {len(icons)} icons -> {os.path.relpath(out, root)}')
